pub fn codicon(icon: Codicon, size_px: f32, color: impl Into<Hsla>) -> Svg {
    svg()
        .path(icon.asset_path())
        .size(px(size_px))
        .text_color(color.into())
        .flex_shrink_0()
}

pub fn brand_logo(size_px: f32) -> Img {
    img(BRAND_LOGO_ASSET_PATH).size(px(size_px)).flex_shrink_0()
}
